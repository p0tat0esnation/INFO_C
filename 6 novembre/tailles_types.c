/* ------------------------------------------------------------------------------------- */
/* Taille des variables en langage C : sizeof(<type>)  */

#include <stdio.h>

int main()
{
    printf("Char : %d octets\n", sizeof(char));
    printf("Int : %d octets\n", sizeof(int));
    printf("Float : %d octets\n", sizeof(float));
    return 0;
}
